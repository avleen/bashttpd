#!/usr/bin/env bash
#
# scripts/build-single.sh -- build a fully self-contained single-file bashttpd.
#
# The modular tree (bin/bashttpd + lib/bashttpd/*.sh) is convenient to hack on
# but awkward to distribute. This script inlines the library modules into the
# CLI entrypoint to produce dist/bashttpd: one file that behaves identically to
# bin/bashttpd for every subcommand, needs neither lib/ nor BASHTTPD_LIB_DIR at
# runtime, and can be dropped anywhere on its own (e.g. curled from a release).
#
# How the inlining works
# ----------------------
# bin/bashttpd wraps its library-location + load_lib block in a pair of marker
# comments:
#
#     # @@INLINE_LIBS_BEGIN@@
#     ... locate REPO_DIR/LIB_DIR, define load_lib() { source each module } ...
#     # @@INLINE_LIBS_END@@
#
# The build emits, in order:
#   1. a single `#!/usr/bin/env bash` shebang,
#   2. a generated-file header (version + source revision + build date),
#   3. every lib module concatenated in dependency order (core, http, mime,
#      router, handlers, server), with only the redundant per-file
#      `# shellcheck shell=bash` directive stripped, and
#   4. bin/bashttpd's own body, with its shebang dropped and the marked block
#      replaced by a stub that keeps SELF/REPO_DIR/LIB_DIR defined (still used
#      by other subcommands) and turns load_lib into a no-op, since the modules
#      are already present above.
#
# The result is shellcheck-clean under a single shebang.

set -euo pipefail

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
REPO_ROOT=$(cd -- "$SCRIPT_DIR/.." && pwd)

SRC_BIN="$REPO_ROOT/bin/bashttpd"
SRC_LIB_DIR="$REPO_ROOT/lib/bashttpd"
OUT_DIR="$REPO_ROOT/dist"
OUT="$OUT_DIR/bashttpd"

# Dependency order: core first (constants/logging), server last (request loop).
MODULES=(core http mime router handlers server)

BEGIN_MARKER='# @@INLINE_LIBS_BEGIN@@'
END_MARKER='# @@INLINE_LIBS_END@@'

# --- Sanity checks -----------------------------------------------------------
[[ -r $SRC_BIN ]] || { printf 'build-single: missing %s\n' "$SRC_BIN" >&2; exit 1; }
for m in "${MODULES[@]}"; do
    [[ -r "$SRC_LIB_DIR/$m.sh" ]] || {
        printf 'build-single: missing %s\n' "$SRC_LIB_DIR/$m.sh" >&2; exit 1
    }
done
if ! grep -qF "$BEGIN_MARKER" "$SRC_BIN" || ! grep -qF "$END_MARKER" "$SRC_BIN"; then
    printf 'build-single: %s is missing the @@INLINE_LIBS@@ markers\n' "$SRC_BIN" >&2
    exit 1
fi

# --- Gather build metadata ---------------------------------------------------
version=$(sed -n "s/^BASHTTPD_VERSION='\\(.*\\)'.*/\\1/p" "$SRC_LIB_DIR/core.sh" | head -1)
[[ -n $version ]] || version='unknown'

# Source revision: nice to have, but the build must work outside a git checkout.
revision='unknown'
if command -v git >/dev/null 2>&1 &&
   git -C "$REPO_ROOT" rev-parse --git-dir >/dev/null 2>&1; then
    revision=$(git -C "$REPO_ROOT" describe --tags --always --dirty 2>/dev/null) || revision=''
    [[ -n $revision ]] || revision=$(git -C "$REPO_ROOT" rev-parse --short HEAD 2>/dev/null) || revision='unknown'
fi

# Reproducible-ish build date; SOURCE_DATE_EPOCH honored when set.
if [[ -n ${SOURCE_DATE_EPOCH:-} ]]; then
    build_date=$(date -u -d "@$SOURCE_DATE_EPOCH" '+%Y-%m-%dT%H:%M:%SZ' 2>/dev/null ||
                 date -u -r "$SOURCE_DATE_EPOCH" '+%Y-%m-%dT%H:%M:%SZ' 2>/dev/null || echo unknown)
else
    build_date=$(date -u '+%Y-%m-%dT%H:%M:%SZ')
fi

# --- Replacement for the marked lib-loading block ----------------------------
read -r -d '' INLINE_STUB <<'STUB' || true
# --- Locate ourselves (single-file build; libraries are inlined above) ------
# This is a generated, self-contained build. SELF/REPO_DIR/LIB_DIR are kept
# because other subcommands still reference them, but no lib/ directory or
# BASHTTPD_LIB_DIR environment variable is required at runtime.
SELF=$(readlink -f "${BASH_SOURCE[0]}")
BIN_DIR=${SELF%/*}
REPO_DIR=${BIN_DIR%/*}
LIB_DIR=$BIN_DIR/lib/bashttpd

# The library modules are inlined at the top of this file, so loading them is
# a no-op here.
load_lib() { :; }
STUB

# --- Emit the single file ----------------------------------------------------
mkdir -p "$OUT_DIR"

{
    printf '#!/usr/bin/env bash\n'
    printf '#\n'
    printf '# bashttpd %s -- single-file build. GENERATED by scripts/build-single.sh.\n' "$version"
    printf '# DO NOT EDIT: change bin/bashttpd or lib/bashttpd/*.sh and rebuild with: make build\n'
    printf '#\n'
    printf '#   source revision: %s\n' "$revision"
    printf '#   built (UTC):     %s\n' "$build_date"
    printf '#\n'
    # File-wide: the modules share state through well-known globals whose
    # cross-function producers/consumers are invisible to static analysis.
    printf '# shellcheck disable=SC2034\n'
    printf '#\n'

    for m in "${MODULES[@]}"; do
        printf '# ===================== lib/bashttpd/%s.sh =====================\n' "$m"
        grep -v '^# shellcheck shell=bash$' "$SRC_LIB_DIR/$m.sh"
        printf '\n'
    done

    printf '# ===================== bin/bashttpd =====================\n'
    # Drop the shebang (first line) and swap the marked block for the stub.
    awk -v begin="$BEGIN_MARKER" -v end="$END_MARKER" -v stub="$INLINE_STUB" '
        NR == 1 && /^#!/ { next }         # drop the original shebang
        $0 == begin { print stub; skip = 1; next }
        $0 == end   { skip = 0; next }
        # The version subcommand references lib/bashttpd/core.sh via a shellcheck
        # source= hint; that path is meaningless once the module is inlined, so
        # point the directive at /dev/null to stay lint-clean (the guarded
        # source is harmless dead code here -- the constant is already set).
        $0 == "        # shellcheck source=lib/bashttpd/core.sh" {
            print "        # shellcheck source=/dev/null"; next
        }
        !skip
    ' "$SRC_BIN"
} > "$OUT"

chmod +x "$OUT"

printf 'build-single: wrote %s (bashttpd %s, %s)\n' "$OUT" "$version" "$revision" >&2
